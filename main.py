#!/usr/bin/env python3
"""One Line, Lights Out — a make.fun entry.

Prints exactly one original funny line about the lights going out:
bedtime, the dark, and the last light in the house giving up.
Python 3.13 standard library only; no dependencies, no arguments.
"""

LINE = (
    "The lights went out, the Wi-Fi died, and suddenly the whole "
    "family remembered how to talk to each other again."
)


def main() -> None:
    print(LINE)


if __name__ == "__main__":
    main()
